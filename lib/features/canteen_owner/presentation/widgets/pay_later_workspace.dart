class PayLaterWorkspace extends StatefulWidget {
  const PayLaterWorkspace({
    required this.canteens,
    required this.initialCanteenId,
    required this.onCanteenChanged,
    required this.onSessionExpired,
    super.key,
  });

  final List<Canteen> canteens;
  final String? initialCanteenId;
  final ValueChanged<String> onCanteenChanged;
  final Future<void> Function() onSessionExpired;

  @override
  State<PayLaterWorkspace> createState() => _PayLaterWorkspaceState();
}

class _PayLaterWorkspaceState extends State<PayLaterWorkspace> {
  List<PayLaterEmployee> _employees = [];
  PayLaterSummary _summary = const PayLaterSummary(
    employeeCount: 0,
    orderCount: 0,
    totalOutstanding: 0,
  );
  String? _canteenId;
  String? _processingKey;
  String? _error;
  bool _loading = true;

  @override
  void initState() {
    super.initState();
    _canteenId = widget.canteens.any((c) => c.id == widget.initialCanteenId)
        ? widget.initialCanteenId
        : (widget.canteens.isEmpty ? null : widget.canteens.first.id);
    _load();
  }

  Future<void> _load() async {
    if (_canteenId == null) {
      setState(() => _loading = false);
      return;
    }
    setState(() {
      _loading = true;
      _error = null;
    });
    try {
      final result = await OrderService.instance.getPayLaterEmployees(
        canteenId: _canteenId,
      );
      if (mounted) {
        setState(() {
          _employees = result.employees;
          _summary = result.summary;
        });
      }
    } on ApiException catch (error) {
      if (!mounted) return;
      if (error.statusCode == 401 || error.statusCode == 403) {
        await widget.onSessionExpired();
        return;
      }
      setState(() => _error = error.message);
    } catch (_) {
      if (mounted)
        setState(() => _error = 'Unable to load Pay Later accounts.');
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  Future<void> _settleAll(PayLaterEmployee employee) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Confirm full payment?'),
        content: Text(
          'Mark all ${employee.orderCount} bills for ${employee.customerName} '
          '(₹${_money(employee.totalOutstanding)}) as paid?',
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, true),
            child: const Text('Payment received'),
          ),
        ],
      ),
    );
    if (confirmed != true) return;
    setState(() => _processingKey = employee.employeeKey);
    try {
      await OrderService.instance.settleEmployeePayLater(
        customerName: employee.customerName,
        mobile: employee.mobile,
        canteenId: _canteenId,
      );
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('All outstanding bills marked as paid.'),
          backgroundColor: AppColors.success,
        ),
      );
      await _load();
    } on ApiException catch (error) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(error.message),
          backgroundColor: AppColors.error,
        ),
      );
    } finally {
      if (mounted) setState(() => _processingKey = null);
    }
  }

  Future<void> _shareReceipt(PayLaterEmployee employee) async {
    final buffer = StringBuffer()
      ..writeln('BookFood Pay Later Receipt')
      ..writeln('Employee: ${employee.customerName}')
      ..writeln('Mobile: ${employee.mobile}')
      ..writeln('Bills: ${employee.orderCount}')
      ..writeln('Total outstanding: ₹${_money(employee.totalOutstanding)}')
      ..writeln();
    for (final order in employee.orders) {
      buffer.writeln('${order.orderNumber} · ${order.canteenName} · ₹${_money(order.grandTotal)}');
      for (final item in order.items) {
        buffer.writeln('  ${item.quantity} × ${item.name} · ₹${_money(item.lineTotal)}');
      }
    }
    buffer
      ..writeln()
      ..writeln('Generated by BookFood');

    final mobile = employee.mobile.replaceAll(RegExp(r'\D'), '');
    final uri = Uri.parse(
      'https://wa.me/91$mobile?text=${Uri.encodeComponent(buffer.toString())}',
    );
    if (!await launchUrl(uri, mode: LaunchMode.externalApplication) && mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Unable to open WhatsApp.')),
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    if (_loading) return const Center(child: CircularProgressIndicator());
    if (_error != null) {
      return Center(
        child: FilledButton(onPressed: _load, child: Text(_error!)),
      );
    }
    if (widget.canteens.isEmpty) {
      return const Center(child: Text('Create a canteen first.'));
    }

    return RefreshIndicator(
      onRefresh: _load,
      child: DashboardPage(
        child: ListView(
          physics: const AlwaysScrollableScrollPhysics(),
          padding: const EdgeInsets.fromLTRB(24, 26, 24, 40),
          children: [
            LayoutBuilder(
              builder: (context, constraints) {
                final title = const Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'Pay Later',
                      style: TextStyle(
                        fontSize: 28,
                        fontWeight: FontWeight.w800,
                      ),
                    ),
                    SizedBox(height: 4),
                    Text(
                      'Outstanding employee accounts',
                      style: TextStyle(color: AppColors.textSecondary),
                    ),
                  ],
                );
                final selector = CanteenSelector(
                  canteens: widget.canteens,
                  selectedId: _canteenId,
                  onChanged: (selectedId) async {
                    if (selectedId == null || selectedId == _canteenId) return;
                    setState(() => _canteenId = selectedId);
                    widget.onCanteenChanged(selectedId);
                    await _load();
                  },
                );
                if (constraints.maxWidth < 650) {
                  return Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [title, const SizedBox(height: 16), selector],
                  );
                }
                return Row(
                  children: [
                    Expanded(child: title),
                    SizedBox(width: 310, child: selector),
                    IconButton(
                      onPressed: _load,
                      icon: const Icon(Icons.refresh_rounded),
                    ),
                  ],
                );
              },
            ),
            const SizedBox(height: 22),
            _Summary(summary: _summary),
            const SizedBox(height: 22),
            if (_employees.isEmpty)
              const Padding(
                padding: EdgeInsets.symmetric(vertical: 70),
                child: Column(
                  children: [
                    Icon(
                      Icons.verified_outlined,
                      size: 54,
                      color: AppColors.success,
                    ),
                    SizedBox(height: 14),
                    Text(
                      'No outstanding employee bills',
                      style: TextStyle(
                        fontSize: 18,
                        fontWeight: FontWeight.w700,
                      ),
                    ),
                  ],
                ),
              )
            else
              ..._employees.map(
                (employee) => Padding(
                  padding: const EdgeInsets.only(bottom: 14),
                  child: _EmployeeAccountCard(
                    employee: employee,
                    processing: _processingKey == employee.employeeKey,
                    onShareReceipt: () => _shareReceipt(employee),
                    onSettleAll: () => _settleAll(employee),
                    onSinglePaid: (orderId) async {
                      setState(() => _processingKey = employee.employeeKey);
                      try {
                        await OrderService.instance.updatePayment(
                          orderId,
                          'Paid',
                        );
                        await _load();
                      } finally {
                        if (mounted) setState(() => _processingKey = null);
                      }
                    },
                  ),
                ),
              ),
          ],
        ),
      ),
    );
  }
}

